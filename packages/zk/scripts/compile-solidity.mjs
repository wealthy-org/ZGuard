import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const contractPath = path.resolve(__dirname, "../contracts/ZGuardQuoteVerifier.sol");
const source = fs.readFileSync(contractPath, "utf8");

const input = {
  language: "Solidity",
  sources: {
    "ZGuardQuoteVerifier.sol": { content: source },
  },
  settings: {
    evmVersion: "paris",
    viaIR: true,
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors || []).filter((e) => e.severity === "error");
if (errors.length > 0) {
  console.error(errors);
  process.exit(1);
}

const compiled = output.contracts["ZGuardQuoteVerifier.sol"]["ZGuardQuoteVerifier"];
const abi = compiled.abi;
const bytecode = `0x${compiled.evm.bytecode.object}`;
const deployedBytecode = `0x${compiled.evm.deployedBytecode.object}`;

const artifactTs = `// Auto-generated by scripts/compile-solidity.mjs via solc ${solc.version()}
export const ZGUARD_VERIFIER_ABI = ${JSON.stringify(abi, null, 2)} as const;

export const ZGUARD_VERIFIER_BYTECODE = "${bytecode}" as const;

export const ZGUARD_VERIFIER_DEPLOYED_BYTECODE = "${deployedBytecode}" as const;
`;

const outTsPath = path.resolve(__dirname, "../src/verifier-artifact.ts");
fs.writeFileSync(outTsPath, artifactTs, "utf8");
console.log(
  `[solc] Compiled ZGuardQuoteVerifier.sol -> src/verifier-artifact.ts (bytecode=${bytecode.length} chars, deployed=${deployedBytecode.length} chars)`
);
