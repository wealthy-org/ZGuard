import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const contractPath = path.resolve(__dirname, "../contracts/ZGuardQuoteVerifier.sol");
const source = fs.readFileSync(contractPath, "utf8");

const input = {
  language: "Solidity",
  sources: {
    "ZGuardQuoteVerifier.sol": { content: source },
  },
  settings: {
    evmVersion: "paris",
    viaIR: true,
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
      },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors || []).filter((e) => e.severity === "error");
if (errors.length > 0) {
  console.error(errors);
  process.exit(1);
}

const compiled = output.contracts["ZGuardQuoteVerifier.sol"]["ZGuardQuoteVerifier"];
const abi = compiled.abi;
const bytecode = `0x${compiled.evm.bytecode.object}`;
const deployedBytecode = `0x${compiled.evm.deployedBytecode.object}`;

const artifactTs = `// Auto-generated by scripts/compile-solidity.mjs via solc ${solc.version()}
export const ZGUARD_VERIFIER_ABI = ${JSON.stringify(abi, null, 2)} as const;

export const ZGUARD_VERIFIER_BYTECODE = "${bytecode}" as const;

export const ZGUARD_VERIFIER_DEPLOYED_BYTECODE = "${deployedBytecode}" as const;
`;

const outTsPath = path.resolve(__dirname, "../src/verifier-artifact.ts");
fs.writeFileSync(outTsPath, artifactTs, "utf8");
console.log(
  `[solc] Compiled ZGuardQuoteVerifier.sol -> src/verifier-artifact.ts (bytecode=${bytecode.length} chars, deployed=${deployedBytecode.length} chars)`
);

// --- Halo2 path (gap H7): generated Halo2Verifier (legacy pipeline: its hand-scheduled assembly hits
// stack-too-deep under via-IR, upstream builds it with `solc --optimize`) + the ZGuard wrapper.
const halo2Input = {
  language: "Solidity",
  sources: {
    "Halo2QuoteVerifier.sol": { content: fs.readFileSync(path.resolve(__dirname, "../contracts/Halo2QuoteVerifier.sol"), "utf8") },
    "ZGuardHalo2QuoteVerifier.sol": {
      content: fs.readFileSync(path.resolve(__dirname, "../contracts/ZGuardHalo2QuoteVerifier.sol"), "utf8"),
    },
  },
  settings: {
    evmVersion: "paris",
    viaIR: false,
    optimizer: { enabled: true, runs: 200 },
    metadata: { bytecodeHash: "none" },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const halo2Out = JSON.parse(solc.compile(JSON.stringify(halo2Input)));
const halo2Errors = (halo2Out.errors || []).filter((e) => e.severity === "error");
if (halo2Errors.length > 0) {
  console.error(halo2Errors);
  process.exit(1);
}
const h2v = halo2Out.contracts["Halo2QuoteVerifier.sol"]["Halo2Verifier"];
const h2w = halo2Out.contracts["ZGuardHalo2QuoteVerifier.sol"]["ZGuardHalo2QuoteVerifier"];
const { keccak256 } = await import("viem");
const runtime = Buffer.from(h2v.evm.deployedBytecode.object, "hex");
const codeHash = keccak256(`0x${h2v.evm.deployedBytecode.object}`);
const halo2Ts = `// Auto-generated by scripts/compile-solidity.mjs via solc ${solc.version()} (legacy pipeline, optimizer 200, no metadata hash)
/** keccak256 of the Halo2Verifier runtime bytecode. The verifying key is embedded in that bytecode, so this is the
 *  identity of the Halo2 circuit (used as \`programVKey\` for halo2-kzg attestations and checked via extcodehash). */
export const HALO2_VERIFIER_CODEHASH = "${codeHash}" as const;

export const HALO2_VERIFIER_BYTECODE = "0x${h2v.evm.bytecode.object}" as const;

/** Runtime code; keccak256 of it is HALO2_VERIFIER_CODEHASH (checked against the deployed contract). */
export const HALO2_VERIFIER_DEPLOYED_BYTECODE = "0x${h2v.evm.deployedBytecode.object}" as const;

export const ZGUARD_HALO2_VERIFIER_ABI = ${JSON.stringify(h2w.abi, null, 2)} as const;

export const ZGUARD_HALO2_VERIFIER_BYTECODE = "0x${h2w.evm.bytecode.object}" as const;
`;
fs.writeFileSync(path.resolve(__dirname, "../src/halo2-artifact.ts"), halo2Ts, "utf8");
console.log(`[solc] Compiled Halo2Verifier (${runtime.length} B runtime, codehash ${codeHash}) + ZGuardHalo2QuoteVerifier -> src/halo2-artifact.ts`);
