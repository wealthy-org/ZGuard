//! zguard-halo2 verifier <out.sol>
//! zguard-halo2 prove-fixtures <sp1-quote-fixtures.json> <out.json>
//!
//! Both commands load the pinned SRS (`$ZGUARD_HALO2_SRS` or `srs/kzg_bn254_13.srs`).

use std::time::Instant;

use serde_json::{json, Value};
use zguard_halo2_quote_circuit::{
    prover::{default_srs_path, keygen, load_params, prove, solidity_verifier, verify, SRS_SHA256, SRS_URL},
    Hints, QuoteCircuit, K, MAX_QUOTE, MAX_TX, NUM_INSTANCES,
};
use zguard_quote_rules::{evaluate, public_values};

fn hints_of(f: &Value) -> Hints {
    let h = &f["hints"];
    let b = |k: &str| h[k].as_bool().unwrap_or(false);
    Hints {
        asset_mismatch: b("asset_mismatch"),
        chain_mismatch: b("chain_mismatch"),
        unexpected_approval: b("unexpected_approval"),
        domain_verified: b("domain_verified"),
    }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let cmd = args.get(1).map(String::as_str).unwrap_or("");
    let params = load_params(default_srs_path()).unwrap_or_else(|e| {
        eprintln!("{e}");
        std::process::exit(2)
    });
    let t = Instant::now();
    let pk = keygen(&params);
    eprintln!("keygen k={K}: {:?}", t.elapsed());

    match (cmd, args.len()) {
        ("verifier", 3) => {
            let sol = solidity_verifier(&params, pk.get_vk());
            let header = format!(
                "// SPDX-License-Identifier: MIT\n// GENERATED by `zguard-halo2 verifier` (packages/zk/halo2-quote-circuit) with\n// privacy-scaling-explorations/halo2-solidity-verifier@9e99730 — do not edit by hand.\n// Circuit: ZGuard quote-match (eip3009), k={K}, {NUM_INSTANCES} instances, SHPLONK/Bdfg21, Keccak transcript.\n// SRS: {SRS_URL} (sha256 {SRS_SHA256}).\n"
            );
            let sol = sol.replacen("// SPDX-License-Identifier: MIT\n", "", 1);
            std::fs::write(&args[2], header + &sol).expect("write verifier");
            eprintln!("wrote {}", args[2]);
        }
        ("prove-fixtures", 4) => {
            let fixtures: Vec<Value> = serde_json::from_str(&std::fs::read_to_string(&args[2]).expect("read fixtures")).expect("json");
            let mut out = Vec::new();
            for f in &fixtures {
                let name = f["name"].as_str().unwrap();
                let q = f["quoteJson"].as_str().unwrap().as_bytes();
                let tx = f["txJson"].as_str().unwrap().as_bytes();
                let hints = hints_of(f);
                let reference = evaluate(q, tx, hints);
                let pv = format!("0x{}", hex::encode(public_values(&reference)));
                assert_eq!(pv, f["expectedPublicValues"].as_str().unwrap(), "{name}: quote-rules drifted from fixtures");
                match QuoteCircuit::new(q, tx, hints) {
                    Err(e) => {
                        eprintln!("{name}: not covered ({e:?})");
                        out.push(json!({ "name": name, "covered": false, "verdict": reference.verdict, "mask": reference.rule_bitmask }));
                    }
                    Ok(circuit) => {
                        let o = circuit.outcome();
                        assert_eq!((o.verdict, o.mask), (reference.verdict, reference.rule_bitmask), "{name}: circuit != quote-rules");
                        let instances = circuit.instances();
                        let t = Instant::now();
                        let proof = prove(&params, &pk, circuit);
                        assert!(verify(&params, pk.get_vk(), &proof, &instances), "{name}: native verify failed");
                        eprintln!("{name}: proof {} bytes in {:?}", proof.len(), t.elapsed());
                        out.push(json!({
                            "name": name,
                            "covered": true,
                            "quoteJson": f["quoteJson"],
                            "txJson": f["txJson"],
                            "verdict": o.verdict,
                            "mask": o.mask,
                            "proof": format!("0x{}", hex::encode(&proof)),
                            "expectedPublicValues": pv,
                        }));
                    }
                }
            }
            let doc = json!({
                "description": "Halo2-KZG proofs for the shared quote fixtures (generated by `zguard-halo2 prove-fixtures`). Proofs are randomized; regenerate together with Halo2QuoteVerifier.sol.",
                "k": K,
                "maxQuoteBytes": MAX_QUOTE,
                "maxTxBytes": MAX_TX,
                "numInstances": NUM_INSTANCES,
                "fixtures": out,
            });
            std::fs::write(&args[3], serde_json::to_string_pretty(&doc).unwrap() + "\n").expect("write proofs");
            eprintln!("wrote {}", args[3]);
        }
        _ => {
            eprintln!("usage: zguard-halo2 verifier <out.sol> | prove-fixtures <fixtures.json> <out.json>");
            std::process::exit(1);
        }
    }
}
